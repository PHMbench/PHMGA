#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any, Dict, Iterable, List


def _read_json(path: Path) -> Dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _iter_manifest(path: Path) -> Iterable[Dict[str, Any]]:
    if not path.exists():
        return []
    rows: List[Dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def _extract_metrics(metrics: Dict[str, Any]) -> Dict[str, Any]:
    val_obj = metrics.get("val") if isinstance(metrics.get("val"), dict) else {}
    best_obj = metrics.get("best") if isinstance(metrics.get("best"), dict) else {}
    return {
        "val_acc": metrics.get("val_acc", val_obj.get("val_acc")),
        "val_macro_f1": metrics.get("val_macro_f1", val_obj.get("val_macro_f1")),
        "test_acc": metrics.get("test_acc"),
        "test_macro_f1": metrics.get("test_macro_f1"),
        "best_epoch": metrics.get("best_epoch", best_obj.get("epoch")),
    }


def _to_markdown(rows: List[Dict[str, Any]]) -> str:
    headers = [
        "dataset",
        "llm",
        "ablation",
        "status",
        "val_acc",
        "val_macro_f1",
        "test_acc",
        "test_macro_f1",
        "run_dir",
    ]
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for row in rows:
        values = [str(row.get(h, "")) for h in headers]
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Collect PHMGA matrix experiment results.")
    parser.add_argument(
        "--manifest",
        type=str,
        default="save/paper_matrix/manifest.jsonl",
        help="Path to manifest.jsonl generated by shell matrix runners.",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="save/paper_matrix",
        help="Output directory for result tables.",
    )
    args = parser.parse_args()

    manifest_path = Path(args.manifest).resolve()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    rows: List[Dict[str, Any]] = []
    for record in _iter_manifest(manifest_path):
        metrics_path = Path(str(record.get("metrics_path") or ""))
        metrics = _read_json(metrics_path) if metrics_path.exists() else {}
        dataset_manifest_path = Path(str(record.get("dataset_manifest_path") or ""))
        dataset_manifest = _read_json(dataset_manifest_path) if dataset_manifest_path.exists() else {}
        metric_row = _extract_metrics(metrics)
        row = {
            "dataset": record.get("dataset"),
            "llm": record.get("llm"),
            "ablation": record.get("ablation"),
            "ablation_mode": record.get("ablation_mode"),
            "status": record.get("status"),
            "val_acc": metric_row.get("val_acc"),
            "val_macro_f1": metric_row.get("val_macro_f1"),
            "test_acc": metric_row.get("test_acc"),
            "test_macro_f1": metric_row.get("test_macro_f1"),
            "best_epoch": metric_row.get("best_epoch"),
            "run_dir": record.get("run_dir"),
            "metrics_path": record.get("metrics_path"),
            "dataset_name": dataset_manifest.get("dataset_name"),
            "source_mode": dataset_manifest.get("source_mode"),
            "return_code": record.get("return_code"),
            "case_dir": record.get("case_dir"),
            "preflight_log": record.get("preflight_log"),
            "run_log": record.get("run_log"),
        }
        rows.append(row)

    csv_path = output_dir / "paper_main_results.csv"
    md_path = output_dir / "paper_main_results.md"

    headers = [
        "dataset",
        "llm",
        "ablation",
        "ablation_mode",
        "status",
        "val_acc",
        "val_macro_f1",
        "test_acc",
        "test_macro_f1",
        "best_epoch",
        "dataset_name",
        "source_mode",
        "run_dir",
        "metrics_path",
        "case_dir",
        "preflight_log",
        "run_log",
        "return_code",
    ]
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=headers)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)

    md_path.write_text(_to_markdown(rows), encoding="utf-8")
    print(f"[collect] wrote {csv_path}")
    print(f"[collect] wrote {md_path}")
    print(f"[collect] rows={len(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
